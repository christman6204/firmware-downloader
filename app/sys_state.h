/* app/sys_state.h
 *
 * 互斥量保护的全局系统状态。基于 UCOS-III OSMutex。
 *
 * 状态项：
 *   - 数据源（SD 卡 / MCU Flash）  -> 影响 LED 闪烁周期
 *   - 固件类型（普通 / 工厂）
 *   - 传输锁定标志（防止并发下载）
 *
 * 默认状态：SD_CARD, NORMAL, unlocked=0。
 * Get/Set 模式：Pend 互斥量（阻塞）-> 读写本地 -> Post 互斥量 -> 返回。
 *
 * 依赖 UCOS-III（os.h），无法在 PC 端测试，仅保证 C 逻辑正确。
 */
#ifndef __SYS_STATE_H
#define __SYS_STATE_H

#include <stdint.h>

/*---------------------------------------------------------------------------*/
/* 数据源                                                                     */
/*---------------------------------------------------------------------------*/
typedef enum {
    DATA_SRC_SD_CARD   = 0u,
    DATA_SRC_MCU_FLASH = 1u
} DataSource_t;

/*---------------------------------------------------------------------------*/
/* 固件类型（与 app_cfg.h 的 FW_TYPE_NORMAL/FW_TYPE_FACTORY 值一致）          */
/*---------------------------------------------------------------------------*/
typedef enum {
    FW_NORMAL  = 0u,
    FW_FACTORY = 1u
} FwType_t;

/*---------------------------------------------------------------------------*/
/* 初始化：创建互斥量（"State Mutex"），置默认状态                            */
/* SD_CARD / NORMAL / unlocked=0。须在 OSStart 后的任务上下文调用。           */
/*---------------------------------------------------------------------------*/
void         SysState_Init(void);

/*---------------------------------------------------------------------------*/
/* 数据源 Get/Set                                                             */
/*---------------------------------------------------------------------------*/
DataSource_t SysState_GetDataSource(void);
void         SysState_SetDataSource(DataSource_t src);

/*---------------------------------------------------------------------------*/
/* 固件类型 Get/Set                                                           */
/*---------------------------------------------------------------------------*/
FwType_t     SysState_GetFwType(void);
void         SysState_SetFwType(FwType_t type);

/*---------------------------------------------------------------------------*/
/* 传输锁定 Get/Set（locked: 0=未锁, 非0=已锁）                               */
/*---------------------------------------------------------------------------*/
uint8_t      SysState_IsTransferLocked(void);
void         SysState_SetTransferLock(uint8_t locked);

/*---------------------------------------------------------------------------*/
/* LED 闪烁周期（ms）：SD_CARD=500, MCU_FLASH=1500                            */
/*---------------------------------------------------------------------------*/
uint32_t     SysState_GetLEDBlinkPeriod(void);

#endif /* __SYS_STATE_H */
